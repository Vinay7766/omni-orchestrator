// A7 / SKL-7 / SKL-9: writes docs/skill-coverage.md from skills/catalog.json and skills/domains.json.
// The report is generated; change the JSON files and run `npm run skills:coverage`, never edit the report.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const REPORT_PATH = "docs/skill-coverage.md";

export function renderCoverage(catalog, domainsDoc) {
  const phasesOf = new Map(domainsDoc.functions.map((f) => [f.id, f.phases.join(", ")]));
  const skillsFor = (domainId) =>
    catalog
      .filter((s) => (s.domains ?? []).includes(domainId))
      .map((s) => s.id)
      .sort();

  const rows = domainsDoc.domains.map((d) => {
    const skills = skillsFor(d.id);
    return { ...d, skills, line: `| ${d.id} | ${d.function} | ${phasesOf.get(d.function) ?? ""} | ${skills.length ? skills.join(", ") : "**gap**"} |` };
  });
  const gaps = rows.filter((r) => r.skills.length === 0);

  return [
    "# Skill coverage",
    "",
    `Generated by \`npm run skills:coverage\` from \`skills/catalog.json\` and \`skills/domains.json\`. Do not edit by hand.`,
    "",
    `${rows.length} domains, ${rows.length - gaps.length} covered, ${gaps.length} gaps.`,
    "",
    "| Domain | Function | Phases | Skills |",
    "|--------|----------|--------|--------|",
    ...rows.map((r) => r.line),
    "",
    "## Gaps",
    "",
    ...(gaps.length ? gaps.map((g) => `- ${g.id}: ${g.description}`) : ["None."]),
    "",
    "## Yardsticks",
    "",
    ...domainsDoc.sources.map((s) => `- [${s.name}](${s.url})`),
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const read = (p) => JSON.parse(readFileSync(resolve(process.cwd(), p), "utf8"));
  const md = renderCoverage(read("skills/catalog.json"), read("skills/domains.json"));
  writeFileSync(resolve(process.cwd(), REPORT_PATH), md);
  console.log(`Wrote ${REPORT_PATH}`);
}
